import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
import basicSsl from '@vitejs/plugin-basic-ssl'
import { createHash } from 'node:crypto'

/**
 * Generates the service-worker source that is emitted as `dist/sw.js`.
 *
 * Self-update strategy (fixes "old app doesn't update until you delete it"):
 *  - The cache name embeds a content hash of this build, so every deploy
 *    installs into a brand-new cache and the activate handler purges every
 *    other cache (including the legacy `tgf-shell-v1` one).
 *  - `skipWaiting()` + `clients.claim()` activate the new worker without
 *    waiting for every tab to close, so already-open installs migrate as soon
 *    as the browser discovers the new `sw.js`.
 *  - Navigations are network-first, so an online client always renders the
 *    fresh `index.html` (which points at the current hashed bundles).
 *  - Hashed JS/CSS bundles are cache-first — safe because their file names
 *    change with their content.
 *  - The app-side registration (src/util/serviceWorker.js) registers with
 *    `updateViaCache: "none"` and checks for updates periodically, so the
 *    browser never trusts an HTTP-cached copy of this file.
 *
 * @param {{ version: string, precache: string[] }} options
 * @returns {string} Service worker source.
 */
export function serviceWorkerSource({ version, precache }) {
  return `/* eslint-disable */
/**
 * Service Worker for Tom & Friends PWA.
 * GENERATED BY \`vite build\` — source of truth: vite.config.js. Do not edit dist/sw.js.
 *
 * Build version: ${version}
 */
const VERSION = ${JSON.stringify(version)};
const CACHE_NAME = "tgf-shell-" + VERSION;
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) =>
      // Tolerant precache: one missing URL must not fail the whole install.
      Promise.all(
        PRECACHE.map((url) =>
          fetch(url, { cache: "reload" })
            .then((res) => (res.ok ? cache.put(url, res) : undefined))
            .catch(() => undefined)
        )
      )
    ).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  const url = new URL(request.url);

  // Cross-origin (Groq / Gemini / GDELT ...): network only, fail soft offline.
  if (url.origin !== self.location.origin) {
    event.respondWith(
      fetch(request).catch(
        () =>
          new Response(JSON.stringify({ error: "Offline" }), {
            status: 503,
            headers: { "Content-Type": "application/json" },
          })
      )
    );
    return;
  }

  // Navigations: network-first so a deployed update is picked up immediately.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, clone)).catch(() => undefined);
            return response;
          }
          // 304 revalidation must never reach the document — serve the copy we hold.
          if (response.status === 304) {
            return caches.match(request).then((cached) => cached || response);
          }
          return response;
        })
        .catch(() =>
          caches.match(request).then((cached) => cached || caches.match("/index.html"))
        )
    );
    return;
  }

  // Same-origin static assets: cache-first (file names are content-hashed).
  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok) {
          const clone = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, clone)).catch(() => undefined);
        }
        return response;
      });
    })
  );
});
`
}

/**
 * Vite plugin: emit a build-versioned `sw.js` next to the hashed bundles.
 * The previous `public/sw.js` was a static placeholder that never changed
 * between deploys, so browsers kept serving the old cache-first shell forever.
 * @returns {import('vite').Plugin}
 */
export function serviceWorkerPlugin() {
  return {
    name: 'tf:service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const hash = createHash('sha256')
      /** @type {string[]} */
      const precache = ['/', '/index.html', '/manifest.json', '/group.png']

      for (const [fileName, output] of Object.entries(bundle)) {
        if (fileName === 'sw.js' || fileName.endsWith('.map')) continue
        hash.update(fileName)
        hash.update(
          output.type === 'chunk'
            ? output.code
            : typeof output.source === 'string' || output.source instanceof Uint8Array
              ? output.source
              : ''
        )
        if (/\.(js|css)$/.test(fileName)) precache.push('/' + fileName)
      }

      const version = hash.digest('hex').slice(0, 12)
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: serviceWorkerSource({ version, precache }),
      })
    },
  }
}

// https://vite.dev/config/
export default defineConfig({
  plugins: [
    react(),
    basicSsl(),
    serviceWorkerPlugin()
  ],server: {
    host: true // Exposes the server on your local network
  }
})
