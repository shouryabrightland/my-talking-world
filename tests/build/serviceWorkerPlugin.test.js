// @ts-check

/**
 * @file serviceWorkerPlugin.test.js
 * Guards the PWA self-update fix: `vite build` must emit a `sw.js` whose
 * cache version is derived from the build content (so every deploy busts the
 * old cache-first shell) and which activates via skipWaiting + clients.claim
 * with network-first navigations.
 */

import { describe, it, expect } from "vitest";
import { serviceWorkerPlugin, serviceWorkerSource } from "../../vite.config.js";

/**
 * Runs the plugin's generateBundle against a fake bundle.
 * @param {Record<string, { type: string, code?: string, source?: string|Uint8Array }>} bundle
 * @returns {Array<{ type: string, fileName?: string, source?: string }>}
 */
function generateSw(bundle) {
    /** @type {Array<{ type: string, fileName?: string, source?: string }>} */
    const emitted = [];
    const ctx = {
        /**
         * @param {{ type: string, fileName?: string, source?: string }} asset
         */
        emitFile(asset) {
            emitted.push(asset);
        },
    };
    // @ts-expect-error — minimal generateBundle context for the unit under test
    serviceWorkerPlugin().generateBundle.call(ctx, {}, bundle);
    return emitted;
}

/** Sample build output with hashed entry assets. */
const sampleBundle = {
    "index.html": { type: "asset", source: "<!doctype html><html>…</html>" },
    "assets/index-ABC123.js": { type: "chunk", code: "console.log('app')" },
    "assets/index-ABC123.css": { type: "asset", source: "body{}" },
    "assets/index-ABC123.js.map": { type: "asset", source: "{}" },
};

describe("serviceWorkerPlugin", () => {
    it("emits a single versioned sw.js", () => {
        const emitted = generateSw(sampleBundle);

        expect(emitted).toHaveLength(1);
        expect(emitted[0].fileName).toBe("sw.js");
        expect(emitted[0].type).toBe("asset");
        expect(emitted[0].source).toMatch(/const VERSION = "[0-9a-f]{12}";/);
        expect(emitted[0].source).toContain("GENERATED BY `vite build`");
    });

    it("precaches the shell and the hashed bundles, but never source maps", () => {
        const source = generateSw(sampleBundle)[0].source || "";

        expect(source).toContain('"/"');
        expect(source).toContain('"/index.html"');
        expect(source).toContain('"/manifest.json"');
        expect(source).toContain('"/assets/index-ABC123.js"');
        expect(source).toContain('"/assets/index-ABC123.css"');
        expect(source).not.toContain(".js.map");
    });

    it("stamps a different version whenever the build content changes", () => {
        const first = generateSw(sampleBundle)[0].source || "";
        const second = generateSw({
            ...sampleBundle,
            "assets/index-ABC123.js": { type: "chunk", code: "console.log('changed')" },
        })[0].source || "";

        const versionOf = (/** @type {string} */ src) =>
            src.match(/const VERSION = "([0-9a-f]{12})";/)?.[1];

        expect(versionOf(first)).toBeTruthy();
        expect(versionOf(first)).not.toBe(versionOf(second));

        // Deterministic: identical bundle → identical version.
        const again = generateSw(sampleBundle)[0].source || "";
        expect(versionOf(again)).toBe(versionOf(first));
    });

    it("uses skipWaiting + clients.claim and network-first navigations", () => {
        const source = generateSw(sampleBundle)[0].source || "";

        expect(source).toContain("self.skipWaiting()");
        expect(source).toContain("self.clients.claim()");
        expect(source).toContain('request.mode === "navigate"');
        expect(source).toContain('caches.delete(key)');
        // Legacy cache names must not survive an activation.
        expect(source).not.toContain("tgf-shell-v1");
    });
});

describe("serviceWorkerSource", () => {
    it("embeds the requested version and precache list verbatim", () => {
        const source = serviceWorkerSource({
            version: "deadbeef0000",
            precache: ["/", "/index.html"],
        });

        expect(source).toContain('const VERSION = "deadbeef0000";');
        expect(source).toContain('const CACHE_NAME = "tgf-shell-" + VERSION;');
        expect(source).toContain('"/index.html"');
    });
});
